// scripts/validate-agents-md.ts
//
// Doc-as-code checker (US-001, CAM-61 PRD).
//
// Treats three classes of command/script/path claims embedded in backtick
// spans of the repo's own agent docs as machine-checkable assertions, so a
// stale reference (the 2026-06-05 stale-comment lesson, see
// scripts/cam/patterns.archive.md) fails a gate instead of silently rotting.
//
// Scanned surface (and ONLY this surface):
//   - CLAUDE.md (repo root)
//   - scripts/cam/CLAUDE.md
//   - .claude/agents/*.md
//
// templates/** is never scanned: its scripts/cam/... references resolve
// against a materialized target project, not this repo (US-001 notes).
//
// Claim classes, in priority order per backtick span:
//   1. `cam <cmd>` -- first word after "cam" validated against the COMMANDS
//      array exported by index.ts.
//   2. `bun run <script>` -- the script token validated against
//      package.json's `scripts` keys.
//   3. Backtick path-claims -- validated against the filesystem (see
//      isPathClaimCandidate / resolvesOnDisk below).
//
// KNOWN_MISSING is an inline allowlist of glob-capable { pattern, reason }
// entries exempting runtime-created artifacts that never exist in a fresh
// checkout. Any entry that matches nothing during a run is reported as a
// non-fatal warning (dead-allowlist-entry guard) -- it does not fail the run.
//
// Usage: bun scripts/validate-agents-md.ts

import { Glob } from 'bun';
import { join } from 'node:path';
import process from 'node:process';
import { COMMANDS } from '../index.ts';

// ---------------------------------------------------------------------------
// Scan surface
// ---------------------------------------------------------------------------

/** Fixed, non-glob doc files scanned every run (repo-root relative). */
export const SCAN_FILES = ['CLAUDE.md', 'scripts/cam/CLAUDE.md'] as const;

/** Glob for the agent persona files. Single `*` -- never recurses into subdirs. */
export const AGENTS_GLOB = '.claude/agents/*.md';

/**
 * Resolve the full list of repo-relative doc paths to scan this run.
 * templates/** is never part of this list by construction: it is not one of
 * SCAN_FILES and does not match AGENTS_GLOB.
 */
export function resolveScanTargets(cwd: string): string[] {
	const targets: string[] = [...SCAN_FILES];
	const glob = new Glob(AGENTS_GLOB);
	for (const file of glob.scanSync({ cwd, dot: true })) {
		targets.push(file);
	}
	return targets.sort();
}

