// ---------------------------------------------------------------------------
// Backtick span extraction
// ---------------------------------------------------------------------------

const FENCED_CODE_BLOCK_RE = /```[\s\S]*?```/g;

/**
 * Strip fenced code blocks (```...```) so they can never be mis-tokenized by
 * the single-backtick span regex below (a triple-backtick fence is 3
 * consecutive backtick characters, which otherwise pairs up with unrelated
 * single backticks elsewhere in the doc and produces bogus multi-line spans).
 */
export function stripFencedCodeBlocks(text: string): string {
	return text.replace(FENCED_CODE_BLOCK_RE, '');
}

/** Extract the inner text of every `backtick span` in a doc, in order of appearance. */
export function extractBacktickSpans(text: string): string[] {
	const spans: string[] = [];
	const re = /`([^`]+)`/g;
	const withoutFences = stripFencedCodeBlocks(text);
	let match: RegExpExecArray | null;
	while ((match = re.exec(withoutFences)) !== null) {
		const span = match[1];
		if (span !== undefined) spans.push(span);
	}
	return spans;
}

// ---------------------------------------------------------------------------
// cam-cmd claims
// ---------------------------------------------------------------------------

const CAM_CMD_RE = /^cam\s+([A-Za-z][\w-]*)/;

/** If `span` is a `cam <cmd>` claim, return the claimed command token; else undefined. */
export function extractCamCommand(span: string): string | undefined {
	const match = CAM_CMD_RE.exec(span);
	return match?.[1];
}

// ---------------------------------------------------------------------------
// bun-run claims
// ---------------------------------------------------------------------------

const BUN_RUN_RE = /^bun run\s+([\w:-]+)/;

/** If `span` is a `bun run <script>` claim, return the claimed script key; else undefined. */
export function extractBunRunScript(span: string): string | undefined {
	const match = BUN_RUN_RE.exec(span);
	return match?.[1];
}

// ---------------------------------------------------------------------------
// Path-claim heuristic (AC4)
// ---------------------------------------------------------------------------

const PATH_EXT_RE = /\.(ts|tsx|js|json|sh|md)$/;

/**
 * Characters that disqualify a span from being a filesystem path-claim:
 * regex/shell metacharacters (grouping, alternation, redirection, template
 * placeholders, home-dir expansion) plus the explicit '$' from AC4. '*' is
 * deliberately NOT included -- glob-ish spans must still qualify.
 */
const DISALLOWED_METACHAR_RE = /[$^()|\\!?<>{}[\];&'",~]/;

const URL_SCHEME_RE = /^https?:\/\//;

/** True when `span` qualifies as a path-claim candidate per the AC4 heuristic. */
export function isPathClaimCandidate(span: string): boolean {
	if (span.includes(' ')) return false;
	if (DISALLOWED_METACHAR_RE.test(span)) return false;
	if (URL_SCHEME_RE.test(span)) return false;
	return span.includes('/') || PATH_EXT_RE.test(span);
}

const LINE_REF_RE = /:(\d+)(?:-\d+)?$/;

/** Strip a trailing `:NNN` or `:NNN-NNN` line-ref, returning the bare path. */
export function stripLineRef(span: string): string {
	return span.replace(LINE_REF_RE, '');
}

/**
 * Resolve a stripped path-claim against `cwd` on disk. A single Bun.Glob
 * covers literal files, directories, and glob-ish patterns alike: a literal
 * string with no wildcard matches only itself, `dot: true` + `onlyFiles:
 * false` lets it also match dotfile directories (e.g. `.claude/agents`).
 */
export function resolvesOnDisk(path: string, cwd: string): boolean {
	const glob = new Glob(path);
	for (const _ of glob.scanSync({ cwd, dot: true, onlyFiles: false })) {
		return true;
	}
	return false;
}

/** Return the first KNOWN_MISSING entry whose pattern matches `path`, if any. */
export function findKnownMissingMatch(
	path: string,
	entries: readonly KnownMissingEntry[],
): KnownMissingEntry | undefined {
	return entries.find((entry) => new Glob(entry.pattern).match(path));
}

// ---------------------------------------------------------------------------
// Findings
// ---------------------------------------------------------------------------

export interface Finding {
	file: string;
	span: string;
	kind: 'cam-cmd' | 'bun-run' | 'path';
	reason: string;
}

export interface ValidationResult {
	findings: Finding[];
	/** KNOWN_MISSING entries that never matched anything during the run. */
	unusedKnownMissing: KnownMissingEntry[];
}

export interface ValidationOptions {
	commands: readonly string[];
	bunScripts: readonly string[];
	knownMissing: KnownMissingEntry[];
	/** Root directory path-claims resolve against. */
	cwd: string;
}

/** Validate a `cam <cmd>` claim; returns a Finding if the command is unknown. */
function checkCamCmdSpan(file: string, span: string, camCmd: string, commands: readonly string[]): Finding | undefined {
	if (commands.includes(camCmd)) return undefined;
	return { file, span, kind: 'cam-cmd', reason: `unknown cam command "${camCmd}"` };
}

/** Validate a `bun run <script>` claim; returns a Finding if the script key is unknown. */
function checkBunRunSpan(
	file: string,
	span: string,
	bunScript: string,
	bunScripts: readonly string[],
): Finding | undefined {
	if (bunScripts.includes(bunScript)) return undefined;
	return { file, span, kind: 'bun-run', reason: `unknown package.json script "${bunScript}"` };
}

/**
 * Validate a backtick path-claim span. Returns a Finding on failure, or
 * marks `matchedEntry` (via the returned `usedEntry`) when the claim is
 * exempted by the KNOWN_MISSING allowlist instead of resolving on disk.
 */
function checkPathSpan(
	file: string,
	span: string,
	options: ValidationOptions,
): { finding?: Finding; usedEntry?: KnownMissingEntry } {
	if (!isPathClaimCandidate(span)) return {};

	const strippedPath = stripLineRef(span);
	if (resolvesOnDisk(strippedPath, options.cwd)) return {};

	const usedEntry = findKnownMissingMatch(strippedPath, options.knownMissing);
	if (usedEntry !== undefined) return { usedEntry };

	return {
		finding: {
			file,
			span,
			kind: 'path',
			reason: `path claim "${strippedPath}" does not resolve on disk and is not allowlisted`,
		},
	};
}

/** Classify and validate a single backtick span against all three claim classes. */
function checkSpan(
	file: string,
	span: string,
	options: ValidationOptions,
): { finding?: Finding; usedEntry?: KnownMissingEntry } {
	const camCmd = extractCamCommand(span);
	if (camCmd !== undefined) return { finding: checkCamCmdSpan(file, span, camCmd, options.commands) };

	const bunScript = extractBunRunScript(span);
	if (bunScript !== undefined) return { finding: checkBunRunSpan(file, span, bunScript, options.bunScripts) };

	return checkPathSpan(file, span, options);
}

/**
 * Validate a set of in-memory docs (each { path, text }) against the three
 * claim classes. Pure with respect to the filesystem except for
 * `resolvesOnDisk`, which reads `options.cwd` -- callers inject a temp
 * directory in tests so results never depend on the live repo staying static.
 */
export function validateDocs(
	docs: { path: string; text: string }[],
	options: ValidationOptions,
): ValidationResult {
	const findings: Finding[] = [];
	const usedKnownMissing = new Set<KnownMissingEntry>();

	for (const doc of docs) {
		for (const span of extractBacktickSpans(doc.text)) {
			const { finding, usedEntry } = checkSpan(doc.path, span, options);
			if (finding !== undefined) findings.push(finding);
			if (usedEntry !== undefined) usedKnownMissing.add(usedEntry);
		}
	}

	const unusedKnownMissing = options.knownMissing.filter((entry) => !usedKnownMissing.has(entry));
	return { findings, unusedKnownMissing };
}

// ---------------------------------------------------------------------------
// CLI entrypoint
// ---------------------------------------------------------------------------

async function main(): Promise<number> {
	const cwd = process.cwd();
	const targets = resolveScanTargets(cwd);
	const docs = await Promise.all(
		targets.map(async (path) => ({ path, text: await Bun.file(join(cwd, path)).text() })),
	);
	const pkgJson = JSON.parse(await Bun.file(join(cwd, 'package.json')).text()) as {
		scripts?: Record<string, string>;
	};

	const result = validateDocs(docs, {
		commands: COMMANDS,
		bunScripts: Object.keys(pkgJson.scripts ?? {}),
		knownMissing: KNOWN_MISSING,
		cwd,
	});

	for (const finding of result.findings) {
		process.stderr.write(`validate-agents-md: ${finding.file}: ${finding.reason} (span: \`${finding.span}\`)\n`);
	}

	for (const entry of result.unusedKnownMissing) {
		process.stderr.write(
			`validate-agents-md: warning: KNOWN_MISSING entry "${entry.pattern}" matched nothing this run\n`,
		);
	}

	if (result.findings.length > 0) return 1;
	process.stdout.write('validate-agents-md: ok\n');
	return 0;
}

if (import.meta.main) {
	main().then((code) => process.exit(code));
}
